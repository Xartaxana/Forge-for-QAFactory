"""Generated AGENTS.md: the Claude Code rules of this repository for a developer working in OpenAI Codex.

Codex reads AGENTS.md, not CLAUDE.md, and has no import syntax, so this script inlines CLAUDE.md
and its whole-line `@path` imports into one file, and appends a Codex setup section built from
.claude/settings.json (hooks) and .claude/agents/*.md (roles). It is generated, never hand-edited;
`--check` compares it byte-for-byte with the file on disk so a pre-commit hook can refuse a commit
where the sources changed and AGENTS.md did not.

    python tools/agents_md.py            write AGENTS.md at the repo root
    python tools/agents_md.py --check    exit 1 if AGENTS.md is stale or missing

Exit codes: 0 ok, 1 stale or missing (--check), 2 a source is malformed, missing or unreadable.
Paths resolve from this file's location (repo root = parent of tools/), never from the cwd;
`--repo <dir>` points the script at another tree (tests).
"""
import argparse
import ast
import json
import os
import pathlib
import re
import sys

_TOOLS_DIR = pathlib.Path(__file__).resolve().parent
if str(_TOOLS_DIR) not in sys.path:
    sys.path.insert(0, str(_TOOLS_DIR))
import md_table  # noqa: E402  (the one fence reader)

REPO = pathlib.Path(__file__).resolve().parent.parent
OUT_NAME = "AGENTS.md"
ENTRY_NAME = "CLAUDE.md"
SETTINGS_REL = ".claude/settings.json"
AGENTS_REL = ".claude/agents"
VALIDATOR_REL = "tools/journal_validator.py"
MAX_DEPTH = 5
CODEX_LIMIT_STEP = 16384

IMPORT_RE = re.compile(r"^@(\S+)$")
HOOK_SCRIPT_RE = re.compile(r"^python\s+tools/([A-Za-z0-9_]+)\.py(?:\s|$)")

HEADER = ("Generated by `python tools/agents_md.py` from CLAUDE.md (+ its imports), "
          ".claude/settings.json and .claude/agents/*.md — do not edit by hand.")
NOTICE = ("This file is {n} bytes; Codex reads only project_doc_max_bytes (32 KiB by default) and "
          "truncates the rest — set `project_doc_max_bytes = {limit}` in your Codex config, "
          "otherwise the rules below are cut off. Codex setup (hooks, roles) is the last section.")


class SourceError(Exception):
    """A source cannot be turned into AGENTS.md; the message names the problem."""


def _read_text(path, shown):
    try:
        raw = pathlib.Path(path).read_bytes().decode("utf-8-sig")
    except (OSError, UnicodeDecodeError) as exc:
        raise SourceError("cannot read %s: %s" % (shown, exc))
    return raw.replace("\r\n", "\n").replace("\r", "\n")


def _rel(repo, path):
    try:
        return pathlib.Path(path).resolve().relative_to(repo.resolve()).as_posix()
    except ValueError:
        return None


# ---------------------------------------------------------------- body: CLAUDE.md with imports

def _expand(repo, path, chain, out):
    """Append the lines of `path` to `out`, expanding whole-line imports outside code fences.
    `chain` = repo-relative paths from CLAUDE.md down to and including `path`."""
    rel = chain[-1]
    # trailing newlines are not content: an end marker sits right against the last text line
    text = _read_text(path, rel).rstrip("\n")
    # the fences are read by md_table.fence_walk, the one fence reader: only a line outside every block ("text") can import
    # (CommonMark: a mark indented by a TAB is not a fence -- the pre-F6-16 regex took `\s{0,3}`, a tab included; pinned in test_md_table.py)
    for lineno, (_idx, line, role) in enumerate(md_table.fence_walk(text.split("\n") if text else []), 1):
        im = IMPORT_RE.match(line.rstrip()) if role == "text" else None
        if not im:
            out.append(line)
            continue
        target = pathlib.Path(os.path.normpath(os.path.join(os.path.dirname(str(path)), im.group(1))))
        trel = _rel(repo, target)
        if trel is None:
            raise SourceError("import @%s (%s line %d) points outside the repository"
                              % (im.group(1), rel, lineno))
        if trel in chain:
            raise SourceError("import cycle: %s" % " -> ".join(chain + [trel]))
        if len(chain) > MAX_DEPTH:
            raise SourceError("import depth exceeds %d: %s" % (MAX_DEPTH, " -> ".join(chain + [trel])))
        if not target.is_file():
            raise SourceError("missing import %s (imported from %s line %d)" % (trel, rel, lineno))
        block = []
        _expand(repo, target, chain + [trel], block)
        out.append("<!-- begin %s -->" % trel)
        out.extend(block)
        out.append("<!-- end %s -->" % trel)


def build_body(repo):
    entry = repo / ENTRY_NAME
    if not entry.is_file():
        raise SourceError("missing %s" % ENTRY_NAME)
    lines = []
    _expand(repo, entry, [ENTRY_NAME], lines)
    return lines


# ---------------------------------------------------------------- setup section

def _cell(value):
    return " ".join(str(value).split()).replace("|", "\\|")


def _docstring_first_paragraph(repo, script):
    """The module docstring's first paragraph (up to the first blank line) as one line."""
    path = repo / "tools" / (script + ".py")
    if not path.is_file():
        return "(script not found)"
    try:
        doc = ast.get_docstring(ast.parse(path.read_bytes().decode("utf-8-sig")))
    except (OSError, UnicodeDecodeError, SyntaxError, ValueError):
        return "(no docstring)"
    doc = (doc or "").strip()
    return " ".join(re.split(r"\n\s*\n", doc)[0].split()) if doc else "(no docstring)"


def hooks_rows(repo):
    """[(event, matcher, command, purpose)] from settings.json; [] when it has no hooks."""
    path = repo / SETTINGS_REL
    text = _read_text(path, SETTINGS_REL)
    try:
        data = json.loads(text)
    except ValueError as exc:
        raise SourceError("%s is not valid JSON: %s" % (SETTINGS_REL, exc))
    if not isinstance(data, dict):
        raise SourceError("%s: the top level is not an object" % SETTINGS_REL)
    hooks = data.get("hooks")
    if not hooks:
        return []
    if not isinstance(hooks, dict):
        raise SourceError("%s: \"hooks\" is not an object" % SETTINGS_REL)
    rows = []
    for event, groups in hooks.items():
        if not isinstance(groups, list):
            raise SourceError("%s: hooks.%s is not a list" % (SETTINGS_REL, event))
        for group in groups:
            if not isinstance(group, dict) or not isinstance(group.get("hooks", []), list):
                raise SourceError("%s: hooks.%s has a malformed entry" % (SETTINGS_REL, event))
            matcher = group.get("matcher") or "(none)"
            for hook in group.get("hooks", []):
                if not isinstance(hook, dict):
                    raise SourceError("%s: hooks.%s has a malformed hook" % (SETTINGS_REL, event))
                command = hook.get("command")
                if not isinstance(command, str) or not command.strip():
                    rows.append((event, matcher, "(no command)", "(external command)"))
                    continue
                m = HOOK_SCRIPT_RE.match(command.strip())
                purpose = _docstring_first_paragraph(repo, m.group(1)) if m else "(external command)"
                rows.append((event, matcher, command.strip(), purpose))
    return rows


def _frontmatter(text):
    """{key: value} of the leading `---` block, or None when the file has none."""
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        return None
    fields, key = {}, None
    for line in lines[1:]:
        if line.strip() == "---":
            return fields
        m = re.match(r"^([A-Za-z_][\w-]*):\s*(.*)$", line)
        if m:
            key = m.group(1)
            fields[key] = m.group(2).strip()
        elif key and line.startswith((" ", "\t")) and line.strip():
            fields[key] = (fields[key] + " " + line.strip()).strip()
    return None                       # no closing fence


def roles_rows(repo):
    """[(name, model, tools, description)] for every .claude/agents/*.md, sorted by file name."""
    adir = repo / AGENTS_REL
    files = sorted(adir.glob("*.md"), key=lambda p: p.name.lower()) if adir.is_dir() else []
    rows = []
    for f in files:
        rel = _rel(repo, f) or f.name
        fm = _frontmatter(_read_text(f, rel))
        if fm is None:
            rows.append((f.stem, "(no frontmatter)", "(no frontmatter)", "(no frontmatter)"))
            continue
        rows.append((fm.get("name") or f.stem, fm.get("model") or "(not set)",
                     fm.get("tools") or "(not set)", fm.get("description") or "(not set)"))
    return rows


def tier_words(repo):
    """The keys of TIER_ORDER in tools/journal_validator.py, in declaration order."""
    path = repo / VALIDATOR_REL
    text = _read_text(path, VALIDATOR_REL)
    try:
        tree = ast.parse(text)
    except SyntaxError as exc:
        raise SourceError("%s does not parse: %s" % (VALIDATOR_REL, exc))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
                isinstance(t, ast.Name) and t.id == "TIER_ORDER" for t in node.targets):
            try:
                value = ast.literal_eval(node.value)
            except ValueError:
                break
            if isinstance(value, dict) and value:
                return [str(k) for k in value]
            break
    raise SourceError("%s has no literal TIER_ORDER dict" % VALIDATOR_REL)


def build_setup(repo):
    rows = hooks_rows(repo)
    roles = roles_rows(repo)
    tiers = tier_words(repo)
    out = ["## Codex setup (this repository is built for Claude Code)", "", "### Hooks", ""]
    if not rows:
        out.append("no hooks configured (%s)." % SETTINGS_REL)
    else:
        out += ["Generated from `%s`." % SETTINGS_REL, "",
                "| Event | Matcher | Command | Purpose |", "|---|---|---|---|"]
        out += ["| %s | `%s` | `%s` | %s |" % (_cell(e), _cell(m), _cell(c), _cell(p))
                for e, m, c, p in rows]
        events, tools = [], []
        for e, m, _, _ in rows:
            if e not in events:
                events.append(e)
            for t in ([] if m == "(none)" else m.split("|")):
                if t and t not in tools:
                    tools.append(t)
        names = "; ".join(["events " + ", ".join(events)] + (["tools " + ", ".join(tools)] if tools else []))
        out += ["",
                "Configure the equivalent Codex hooks. The Claude event and tool names above "
                "(%s) must be mapped to Codex's own; without them the journal, dispatch and "
                "hygiene checks do not run." % names]
    out += ["", "### Git hooks", "",
            "Run once by hand: `git config core.hooksPath .githooks`. (The Claude SessionStart hook "
            "sets it; in Codex nothing does.) The pre-commit and commit-msg gates then run "
            "whatever the agent."]
    out += ["", "### Roles", ""]
    if not roles:
        out.append("no role files in `%s`." % AGENTS_REL)
    else:
        out += ["Generated from the frontmatter of `%s/*.md`." % AGENTS_REL, "",
                "| Role | Model | Tools | Description |", "|---|---|---|---|"]
        out += ["| %s | %s | %s | %s |" % tuple(_cell(v) for v in r) for r in roles]
    out += ["",
            "Codex runs subagents: create one per role, with the role file's body as its "
            "instructions, and bind a GPT model to each role; record the binding in "
            "`delegation.config.yaml`.",
            "",
            "Journal note: the `by` field of `logs/routing-log.jsonl` accepts only the tier words in "
            "`TIER_ORDER` of `%s`: %s. Use the tier word of the FUNCTION level your model serves "
            "(the table in CLAUDE.md \"Tiers\"), and the real model id in `model`. Work done by a "
            "non-Claude model still carries a `basis` on its `accepted` event (\"critic\", "
            "\"queued-to-lead\" or, for a leaf, \"judge\"): the acceptance matrix compares "
            "function-tier words, not model ids, so `basis` supplies what the tier comparison "
            "cannot."
            % (VALIDATOR_REL,", ".join("`%s`" % t for t in tiers))]
    return out


# ---------------------------------------------------------------- assembly

def _limit_for(n):
    return -(-n // CODEX_LIMIT_STEP) * CODEX_LIMIT_STEP


def assemble(body, setup):
    """The final bytes. The notice names the file's own size n, so find n with len(text(n)) == n.
    len(text(n)) never decreases as n grows (more digits, a bigger limit), so starting from the
    smallest possible size and jumping to the current length converges on the least fixed point;
    it always exists, also across a digit-count change."""
    def text(n):
        notice = NOTICE.format(n=n, limit=_limit_for(n))
        lines = [HEADER, "", notice, ""] + body + [""] + setup
        return ("\n".join(lines) + "\n").encode("utf-8")

    n = len(text(0))
    while True:
        data = text(n)
        if len(data) == n:
            return data
        n = len(data)              # len(text(n)) > n here, and it never exceeds the fixed point


def build(repo):
    repo = pathlib.Path(repo)
    return assemble(build_body(repo), build_setup(repo))


def main(argv=None):
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="compare AGENTS.md on disk with a fresh build; never writes")
    ap.add_argument("--repo", type=pathlib.Path, default=REPO, help="repository root (tests)")
    args = ap.parse_args(argv)
    repo = args.repo.resolve()
    out = repo / OUT_NAME

    try:
        data = build(repo)
    except SourceError as exc:
        print("agents md: %s" % exc, file=sys.stderr)
        return 2

    if args.check:
        # The fix command names the tree it checked (--repo <path>), so it regenerates exactly this tree's AGENTS.md
        # from any cwd and from any copy of the script, a git worktree included (B-470).
        fix = "python tools/agents_md.py --repo %s" % (('"%s"' % repo) if " " in str(repo) else repo)
        if not out.is_file():
            print("AGENTS.md is missing: run %s and stage AGENTS.md" % fix)
            return 1
        if out.read_bytes() != data:
            print("AGENTS.md is stale: run %s and stage AGENTS.md" % fix)
            return 1
        print("AGENTS.md: up to date (%d bytes)" % len(data))
        return 0

    out.write_bytes(data)
    print("wrote %s: %d bytes" % (OUT_NAME, len(data)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
