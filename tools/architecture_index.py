"""Compact index of the factory's load-bearing invariants (AR-n), generated from architecture.md.

The source is `ai-packages/qa-factory/design/architecture.md`. The index is one line per invariant
(id and title, grouped by the four goal sections A-D) and is imported into every session through
CLAUDE.md, so it is capped at 3072 bytes. It is generated, never hand-edited; `--check` compares it
byte-for-byte with the file on disk so a pre-commit hook and CI can refuse a commit where the
source changed and the index did not. tools/architecture_gate.py reads the ids from the index.

    python tools/architecture_index.py            write docs/ARCHITECTURE_INDEX.md
    python tools/architecture_index.py --check    exit 1 if the file on disk is stale or missing

Parsing stops at the first `## ` heading that is not `## <Letter>. `: the protocol section after
the four goal sections is not indexed. The summary table ("| Section | Invariants |") before the
first section is cross-checked against the ids found under each heading.

Exit codes: 0 ok, 1 stale or missing (--check), 2 the source is malformed, unreadable, holds more than
30 invariants (the document's step 10) or would produce an index over the byte cap. Paths resolve from this file's location (repo root = parent of
tools/), never from the cwd.
"""
import argparse
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
SOURCE_REL = "ai-packages/qa-factory/design/architecture.md"
OUT_REL = "docs/ARCHITECTURE_INDEX.md"
DEFAULT_SOURCE = REPO / SOURCE_REL
DEFAULT_OUT = REPO / OUT_REL

MAX_BYTES = 3072                      # the boot budget: the index is imported into every session
MAX_INVARIANTS = 30                   # architecture.md "How a change walks this map", step 10
REQUIRED_SECTIONS = "ABCD"            # the owner's four goals, one section each

SECTION_RE = re.compile(r"^## ([A-Z])\. (.+?)\s*$")
OPENER_RE = re.compile(r"^\*\*AR-(\d+)")
TITLE_RE = re.compile(r"^\*\*AR-\d+ — (.*?)\*\*")
ID_RE = re.compile(r"AR-(\d+)")

HEADER = (
    "# Architecture invariants — index\n"
    "\n"
    "Generated by `python tools/architecture_index.py` from `" + SOURCE_REL + "` — do not edit "
    "by hand. One line per invariant; carriers, detector, breakage and change check are in the "
    "source. A change to `ai-packages/qa-factory/` names the AR-n it touches "
    "(`architecture:` line, tools/architecture_gate.py).\n"
)


class SourceError(Exception):
    """The source cannot be turned into an index; the message names the problem."""


def opener_title(line, n):
    """The text of the bold opener after `AR-<n> — `, trailing period dropped."""
    m = TITLE_RE.match(line)
    if not m:
        raise SourceError("AR-%d: the bold opener must read `**AR-%d — <title>**` on one line" % (n, n))
    title = " ".join(m.group(1).split()).rstrip(".").rstrip()
    if not title:
        raise SourceError("AR-%d: the bold opener has an empty title" % n)
    return title


def table_row(line):
    """(section name, [ids]) of a summary-table row, or None for any other line."""
    cells = [c.strip() for c in line.strip().strip("|").split("|")]
    if len(cells) != 2 or not ID_RE.search(cells[1]):
        return None
    return cells[0], [int(n) for n in ID_RE.findall(cells[1])]


def scan(text):
    """(sections, summary): sections = [(letter, name, [(id, title)])] in file order, summary =
    {name: [ids]}. Stops at the first heading that is not `## <Letter>. `. Raises SourceError."""
    sections, summary, first_line = [], {}, {}
    open_section = None
    for number, line in enumerate(text.splitlines(), 1):
        head = SECTION_RE.match(line)
        if head:
            open_section = (head.group(1), head.group(1) + ". " + head.group(2), [])
            sections.append(open_section)
        elif line.startswith("## "):
            break
        elif open_section is None:
            row = table_row(line) if line.startswith("|") else None
            if row:
                summary[row[0]] = row[1]
            if OPENER_RE.match(line):
                raise SourceError("AR-%s (line %d) is an opener before the first `## <Letter>. ` "
                                  "heading" % (OPENER_RE.match(line).group(1), number))
        elif OPENER_RE.match(line):
            n = int(OPENER_RE.match(line).group(1))
            if n == 0:                # tools/architecture_gate.py reads ids as AR-<1-9><digits>
                raise SourceError("AR-0 (line %d): ids start at AR-1" % number)
            if n in first_line:
                raise SourceError("duplicate invariant id AR-%d (lines %d and %d)"
                                  % (n, first_line[n], number))
            first_line[n] = number
            open_section[2].append((n, opener_title(line, n)))
    return sections, summary


def verify(sections, summary):
    """Raise SourceError when the four goal sections are not all there, when no invariant was
    found, or when the summary table and the headings disagree."""
    letters = "".join(letter for letter, _, _ in sections)
    absent = [c for c in REQUIRED_SECTIONS if c not in letters]
    if absent:
        raise SourceError("missing section heading(s): %s (expected `## A.` to `## D.`)"
                          % ", ".join("## %s." % c for c in absent))
    if not any(items for _, _, items in sections):
        raise SourceError("no invariants found (expected lines starting `**AR-<n> — `)")
    problems = []
    names = [name for _, name, _ in sections]
    problems += ["section '%s' has no row in the summary table" % n for n in names if n not in summary]
    problems += ["the summary table lists section '%s' but the file has no such heading" % n
                 for n in summary if n not in names]
    for _, name, items in sections:
        if name not in summary:
            continue
        found = [n for n, _ in items]
        for label, ids in (("listed in the summary table but not found under the heading",
                            sorted(set(summary[name]) - set(found))),
                           ("found under the heading but missing from the summary table",
                            sorted(set(found) - set(summary[name])))):
            if ids:
                problems.append("section '%s': %s: %s" % (name, label, ", ".join("AR-%d" % n for n in ids)))
    if problems:
        raise SourceError("summary table and section headings disagree: " + "; ".join(problems))


def render(sections):
    blocks = [HEADER]
    for _, name, items in sections:
        blocks.append("\n".join(["## " + name] + ["- AR-%d — %s" % item for item in items]) + "\n")
    return "\n".join(blocks)          # one blank line between the header and each section


def build(source_path):
    """(index bytes, invariant count, section count). Raises SourceError."""
    try:
        text = pathlib.Path(source_path).read_bytes().decode("utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        raise SourceError("cannot read the source %s: %s" % (source_path, exc))
    sections, summary = scan(text)
    verify(sections, summary)
    total = sum(len(items) for _, _, items in sections)
    if total > MAX_INVARIANTS:
        raise SourceError("the source has %d invariants, over the %d-entry limit (architecture.md, How a "
                          "change walks this map, step 10): merge the new invariant into its nearest entry"
                          % (total, MAX_INVARIANTS))
    data = render(sections).encode("utf-8")
    if len(data) > MAX_BYTES:
        raise SourceError("the index would be %d bytes, over the %d-byte cap (it is imported into "
                          "every session): shorten titles, or merge a new invariant into its "
                          "nearest entry" % (len(data), MAX_BYTES))
    return data, total, len(sections)


def command_line(argv):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="compare the index on disk with a fresh build; never writes")
    ap.add_argument("--source", type=pathlib.Path, default=DEFAULT_SOURCE)
    ap.add_argument("--out", type=pathlib.Path, default=DEFAULT_OUT)
    return ap.parse_args(argv)


def utf8_output():
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")


def main(argv=None):
    utf8_output()
    args = command_line(argv)
    try:
        data, count, n_sections = build(args.source)
    except SourceError as exc:
        print("architecture index: %s" % exc, file=sys.stderr)
        return 2
    fix = "run python tools/architecture_index.py and stage docs/ARCHITECTURE_INDEX.md"
    if args.check:
        if not args.out.is_file():
            print("architecture index is missing: " + fix)
            return 1
        if args.out.read_bytes() != data:
            print("architecture index is stale: " + fix)
            return 1
        print("architecture index: up to date (%d invariants, %d bytes)" % (count, len(data)))
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_bytes(data)
    print("wrote %s: %d invariants, %d sections, %d bytes"
          % (OUT_REL if args.out == DEFAULT_OUT else args.out, count, n_sections, len(data)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
