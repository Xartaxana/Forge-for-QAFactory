"""Compact index of the factory building rules (FR-n), generated from factory-rules.md.

The source is `ai-packages/qa-factory/design/factory-rules.md`. The index is one line per rule
(id and title, grouped by section) and is small enough to load into every session. It is generated,
never hand-edited; `--check` compares it byte-for-byte with the file on disk so a pre-commit hook
can refuse a commit where the rules changed and the index did not.

    python tools/factory_rules_index.py            write every index of the SOURCES table
    python tools/factory_rules_index.py --check    exit 1 if a file on disk is stale or missing
    python tools/factory_rules_index.py --row P --source X --out Y   one row, paths overridden

The SOURCES table below holds one row per index (FR: the factory rules; P: the owner principles).
Without --row, every row runs; with --source/--out and no --row, the FR row runs (the old form).

Exit codes: 0 ok, 1 stale or missing (--check), 2 the source is malformed, unreadable or over a cap.
Paths resolve from this file's location (repo root = parent of tools/), never from the cwd.
"""
import argparse
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
SOURCE_REL = "ai-packages/qa-factory/design/factory-rules.md"
OUT_REL = "docs/FACTORY_RULES_INDEX.md"
DEFAULT_SOURCE = REPO / SOURCE_REL
DEFAULT_OUT = REPO / OUT_REL

SECTION_RE = re.compile(r"^## ([A-Z]\. .+?)\s*$")
OPENER_RE = re.compile(r"^\*\*FR-(\d+) — ")
ID_RE = re.compile(r"FR-(\d+)")

HEADER = (
    "# Factory building rules — index\n"
    "\n"
    "Generated by `python tools/factory_rules_index.py` from `" + SOURCE_REL + "` — do not edit "
    "by hand. One line per rule; the full rule, its reason and its check are in the source. Every "
    "change to `ai-packages/qa-factory/` walks the sections it touches (PROJECT.md).\n"
)


P_SOURCE_REL = "docs/OWNER_PRINCIPLES.md"
P_OUT_REL = "docs/OWNER_PRINCIPLES_INDEX.md"
P_HEADER = (
    "# Owner principles — index\n"
    "\n"
    "Generated by `python tools/factory_rules_index.py` from `" + P_SOURCE_REL + "` — do not edit "
    "by hand. One line per principle: its number and first sentence; the full text is in the "
    "source. Read the source before changing a rule that leans on a principle.\n"
)

# The data table: one row per index. kind "sections" = lettered sections of bold openers (FR);
# kind "bullets" = flat bullets with a first-sentence line (P). A cap of None means no cap.
SOURCES = [
    {"name": "FR", "kind": "sections", "source": SOURCE_REL, "out": OUT_REL,
     "opener": OPENER_RE.pattern, "header": HEADER, "line_cap": None, "file_cap": None},
    {"name": "P", "kind": "bullets", "source": P_SOURCE_REL, "out": P_OUT_REL,
     "opener": r"^- \*\*P(\d+)\.\*\* ", "header": P_HEADER, "line_cap": 220, "file_cap": 6144},
]
ELLIPSIS = " …"


class SourceError(Exception):
    """The source cannot be turned into an index; the message names the problem."""


def _title(paragraph_lines):
    """The text inside the bold opener, after `FR-<n> — `, up to the closing `**`."""
    text = " ".join(line.strip() for line in paragraph_lines)
    m = OPENER_RE.match(text)
    end = text.find("**", m.end())
    if end < 0:
        raise SourceError("FR-%s: the bold opener has no closing `**`" % m.group(1))
    title = " ".join(text[m.end():end].split())
    if title.endswith("."):
        title = title[:-1].rstrip()
    if not title:
        raise SourceError("FR-%s: the bold opener has an empty title" % m.group(1))
    return title


def parse(text):
    """Return (sections, summary): sections = [(name, [(id, title)])] in file order,
    summary = {name: [ids]} from the summary table. Raises SourceError."""
    lines = text.splitlines()
    sections = []          # [name, [(id, title), ...]]
    summary = {}
    current = None
    seen = {}
    i = 0
    while i < len(lines):
        line = lines[i]
        m = SECTION_RE.match(line)
        if m:
            current = [m.group(1), []]
            sections.append(current)
            i += 1
            continue
        if line.startswith("## "):
            current = None          # an unlettered heading ends the section it follows
            i += 1
            continue
        if current is None and line.startswith("|"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if len(cells) == 2 and ID_RE.search(cells[1]):
                summary[cells[0]] = [int(n) for n in ID_RE.findall(cells[1])]
            i += 1
            continue
        m = OPENER_RE.match(line)
        if m:
            n = int(m.group(1))
            if current is None:
                raise SourceError(
                    "FR-%d (line %d) is an opener before the first `## <Letter>. ` section heading"
                    % (n, i + 1))
            if n in seen:
                raise SourceError("duplicate rule id FR-%d (lines %d and %d)" % (n, seen[n], i + 1))
            seen[n] = i + 1
            para = [line]
            j = i + 1
            while j < len(lines) and lines[j].strip() and not lines[j].startswith("## "):
                para.append(lines[j])
                j += 1
            current[1].append((n, _title(para)))
            i = j
            continue
        i += 1

    if not any(rules for _, rules in sections):
        raise SourceError("no rules found (expected lines starting `**FR-<n> — `)")

    problems = []
    found = {name: [n for n, _ in rules] for name, rules in sections}
    for name in found:
        if name not in summary:
            problems.append("section '%s' has no row in the summary table" % name)
    for name in summary:
        if name not in found:
            problems.append("the summary table lists section '%s' but the file has no such heading"
                            % name)
    for name in found:
        if name not in summary:
            continue
        listed, actual = set(summary[name]), set(found[name])
        missing = sorted(listed - actual)
        extra = sorted(actual - listed)
        if missing:
            problems.append("section '%s': listed in the summary table but not found under the "
                            "heading: %s" % (name, ", ".join("FR-%d" % n for n in missing)))
        if extra:
            problems.append("section '%s': found under the heading but missing from the summary "
                            "table: %s" % (name, ", ".join("FR-%d" % n for n in extra)))
    if problems:
        raise SourceError("summary table and section headings disagree: " + "; ".join(problems))
    return [(name, rules) for name, rules in sections], summary


def render(sections):
    out = [HEADER]
    for name, rules in sections:
        block = ["## %s" % name]
        block += ["- FR-%d — %s" % (n, title) for n, title in rules]
        out.append("\n".join(block) + "\n")
    return "\n".join(out)          # one blank line between the header and each section


def build(source_path):
    try:
        text = pathlib.Path(source_path).read_bytes().decode("utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        raise SourceError("cannot read the source %s: %s" % (source_path, exc))
    sections, _ = parse(text)
    n_rules = sum(len(rules) for _, rules in sections)
    return render(sections).encode("utf-8"), n_rules, len(sections)


def first_sentence(text):
    """Text up to and including the first `.`, `!` or `?` followed by whitespace, outside
    backticks; no sentence end -> the whole text."""
    in_code = False
    for i, ch in enumerate(text):
        if ch == "`":
            in_code = not in_code
        elif not in_code and ch in ".!?" and (i + 1 == len(text) or text[i + 1].isspace()):
            return text[:i + 1]
    return text


def cap_line(prefix, sentence, cap):
    """prefix + sentence as one line of at most `cap` UTF-8 bytes: longer -> cut at the last
    whitespace that fits and append ' …'; never inside a character."""
    line = prefix + sentence
    if len(line.encode("utf-8")) <= cap:
        return line
    budget = cap - len((prefix + ELLIPSIS).encode("utf-8"))
    head = sentence.encode("utf-8")[:max(budget, 0)].decode("utf-8", errors="ignore")
    # the cut may have fallen mid-word: back up to the last whitespace if the next char is not one
    if len(head) < len(sentence) and not sentence[len(head)].isspace():
        k = max(head.rfind(" "), head.rfind("\t"))
        if k > 0:
            head = head[:k]
    return prefix + head.rstrip() + ELLIPSIS


def parse_bullets(text, row):
    """Return [(n, line_no, text)] for the row's opener; raises SourceError."""
    opener = re.compile(row["opener"])
    lines = text.splitlines()
    out, seen = [], {}
    i = 0
    while i < len(lines):
        m = opener.match(lines[i])
        if not m:
            i += 1
            continue
        n = int(m.group(1))
        if n in seen:
            raise SourceError("duplicate id %s%d (lines %d and %d)"
                              % (row["name"], n, seen[n], i + 1))
        seen[n] = i + 1
        parts = [lines[i][m.end():].strip()]
        j = i + 1
        while j < len(lines) and lines[j].strip() and not lines[j].startswith(("- ", "#")):
            parts.append(lines[j].strip())
            j += 1
        body = " ".join(p for p in parts if p)
        if not body:
            raise SourceError("%s%d (line %d) is an empty bullet" % (row["name"], n, i + 1))
        out.append((n, i + 1, body))
        i = j
    if not out:
        raise SourceError("no entries found (expected lines matching %s)" % row["opener"])
    return out


def build_bullets(source_path, row):
    try:
        text = pathlib.Path(source_path).read_bytes().decode("utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        raise SourceError("cannot read the source %s: %s" % (source_path, exc))
    lines = [cap_line("- %s%d — " % (row["name"], n), first_sentence(body), row["line_cap"])
             for n, _, body in parse_bullets(text, row)]
    data = (row["header"] + "\n" + "\n".join(lines) + "\n").encode("utf-8")
    if len(data) > row["file_cap"]:
        longest = sorted(lines, key=lambda ln: len(ln.encode("utf-8")), reverse=True)[:3]
        raise SourceError(
            "the index is %d bytes, over the %d-byte cap; the three longest lines: %s. "
            "Door: shorten the first sentence in the source, or raise the cap in the data row "
            "with a reason" % (len(data), row["file_cap"], " | ".join(longest)))
    return data, len(lines), 1


def build_row(row, source_path):
    if row["kind"] == "bullets":
        return build_bullets(source_path, row)
    return build(source_path)


def _shown(path):
    try:
        return pathlib.Path(path).resolve().relative_to(REPO).as_posix()
    except ValueError:
        return str(path)


def run_row(row, source, out, check):
    """Run one table row; returns its exit code."""
    shown_src = _shown(source)
    if not pathlib.Path(source).is_file() and row["kind"] == "bullets":
        if pathlib.Path(out).is_file():
            print("factory rules index: the index %s exists but its source %s is absent"
                  % (_shown(out), shown_src), file=sys.stderr)
            return 2
        print("skip: %s absent" % shown_src)
        return 0
    try:
        data, n_rules, n_sections = build_row(row, source)
    except SourceError as exc:
        print("factory rules index: %s" % exc, file=sys.stderr)
        return 2

    shown = _shown(out)
    if check:
        if not out.is_file():
            print("factory rules index is missing: run python tools/factory_rules_index.py "
                  "and stage %s" % shown)
            return 1
        if out.read_bytes() != data:
            print("factory rules index is stale: run python tools/factory_rules_index.py "
                  "and stage %s" % shown)
            return 1
        print("factory rules index: up to date (%d rules)" % n_rules)
        return 0

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(data)
    print("wrote %s: %d rules, %d sections, %d bytes" % (shown, n_rules, n_sections, len(data)))
    return 0


def main(argv=None):
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="compare the index on disk with a fresh build; never writes")
    ap.add_argument("--row", choices=[r["name"] for r in SOURCES],
                    help="run one row of the table (default: all; FR when --source/--out is given)")
    ap.add_argument("--source", type=pathlib.Path)
    ap.add_argument("--out", type=pathlib.Path)
    args = ap.parse_args(argv)

    name = args.row
    if name is None and (args.source or args.out):
        name = "FR"
    code = 0
    for row in SOURCES:
        if name and row["name"] != name:
            continue
        source = args.source if (name and args.source) else REPO / row["source"]
        out = args.out if (name and args.out) else REPO / row["out"]
        code = max(code, run_row(row, source, out, args.check))
    return code


if __name__ == "__main__":
    sys.exit(main())
